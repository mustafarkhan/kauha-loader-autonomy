"""Generate the firmware's data files from the single sources in the repository.

    python firmware/generate.py

  common/generated/kauha_machine.{c,h}  frame pack/unpack, from hardware/can/kauha_machine.dbc (cantools)
  common/generated/kinematics.h         actuator length tables and machine geometry, from
                                        hardware/scale/generated/linkage.json and kauha.scale.profile

tests/firmware checks that the committed files are current.
"""
from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GEN = ROOT / "firmware" / "common" / "generated"


def kinematics_header() -> str:
    sys.path.insert(0, str(ROOT))
    from kauha.config import load_machine
    from kauha.scale.profile import scale_machine
    m = scale_machine(load_machine())
    link = json.loads((ROOT / "hardware" / "scale" / "generated" / "linkage.json").read_text())
    out = ["/* Generated by firmware/generate.py from hardware/scale/generated/linkage.json and",
           " * kauha.scale.profile. Do not edit by hand. Units: m, rad. */",
           "#ifndef KAUHA_KINEMATICS_H", "#define KAUHA_KINEMATICS_H", "",
           f"#define KIN_LF {m.lf:.6f}", f"#define KIN_LR {m.lr:.6f}", "#define KIN_TRACK 0.262500",
           f"#define KIN_WHEEL_R {link['wheel_radius']:.6f}", f"#define KIN_MAX_SPEED {m.max_speed:.6f}",
           f"#define KIN_MAX_ACCEL {m.max_accel:.6f}", f"#define KIN_MAX_ARTICULATION {m.max_articulation:.6f}",
           f"#define KIN_ARTICULATION_RATE {m.articulation_rate:.6f}", f"#define KIN_BOOM_RATE {m.boom_rate:.6f}",
           f"#define KIN_BUCKET_RATE {m.bucket_rate:.6f}", ""]
    for name, a in link["actuators"].items():
        n = len(a["angles"])
        lo, hi = a["length_range_m"]
        u = name.upper()
        out += [f"/* {name}: PA-14P {a['stroke_in']:g} in, retracted {lo:.4f} m, extended {hi:.4f} m. {a['note']} */",
                f"#define KIN_{u}_N {n}", f"#define KIN_{u}_RETRACTED {lo:.6f}", f"#define KIN_{u}_EXTENDED {hi:.6f}",
                f"static const double KIN_{u}_ANGLE[{n}] = {{" + ", ".join(f"{x:.6f}" for x in a["angles"]) + "};",
                f"static const double KIN_{u}_LENGTH[{n}] = {{" + ", ".join(f"{x:.6f}" for x in a["lengths"]) + "};",
                ""]
    out += ["#endif", ""]
    return "\n".join(out)


def main() -> None:
    GEN.mkdir(parents=True, exist_ok=True)
    subprocess.run([sys.executable, "-m", "cantools", "generate_c_source", "--database-name", "kauha_machine",
                    "-o", str(GEN), str(ROOT / "hardware" / "can" / "kauha_machine.dbc")], check=True,
                   capture_output=True)
    for f in GEN.glob("kauha_machine.*"):        # drop the generation date so reruns are reproducible
        f.write_text("".join(ln for ln in f.read_text().splitlines(keepends=True) if "generated by cantools" not in ln
                             and "Generation date" not in ln))
    (GEN / "kinematics.h").write_text(kinematics_header())
    print("generated", *sorted(p.name for p in GEN.iterdir()))


if __name__ == "__main__":
    main()
