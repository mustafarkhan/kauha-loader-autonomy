"""Evaluate every validation criterion and write the results table.

    python -m kauha.validation.report            # writes results/validation.json and docs/results/validation.md
    python -m kauha.validation.report --check    # exit 1 if a criterion fails that is not a recorded known failure
"""
from __future__ import annotations

import argparse
import json
from dataclasses import asdict

from kauha.config import REPO_ROOT
from kauha.validation.checks import CHECKS
from kauha.validation.criteria import CRITERIA

JSON = REPO_ROOT / "results" / "validation.json"
MD = REPO_ROOT / "docs" / "results" / "validation.md"
# Failures that are understood and recorded as open design issues. A new failure breaks CI.
KNOWN_FAILURES: set[str] = set()


def run() -> list[dict]:
    rows = []
    for c in CRITERIA:
        r = CHECKS[c.id]()
        rows.append({**asdict(c), "status": r.status, "measured": r.measured, "note": r.note})
    return rows


def markdown(rows: list[dict]) -> str:
    count = {s: sum(r["status"] == s for r in rows) for s in ("pass", "fail", "finding", "open", "needs data")}
    out = ["# External validation results", "",
           "Generated by `python -m kauha.validation.report` from `kauha/validation/criteria.py`. Targets were "
           "fixed before the checks ran. Failures and findings stay in the table.", "",
           f"**{count['pass']} pass, {count['fail']} fail, {count['finding']} finding, {count['open']} open, "
           f"{count['needs data']} need data** of {len(rows)} criteria.", "",
           "| Id | Part | Source | Target | Result | Status |", "|---|---|---|---|---|---|"]
    for r in rows:
        out.append(f"| {r['id']} | {r['part']} | [{r['source']}]({r['url']}) | {r['target']} | "
                   f"{r['measured'] or '-'} | **{r['status']}** |")
    out += ["", "## Notes", ""]
    out += [f"- **{r['id']}** ({r['status']}): {r['note']}" for r in rows if r["note"]]
    return "\n".join(out) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    rows = run()
    new = sorted(r["id"] for r in rows if r["status"] == "fail" and r["id"] not in KNOWN_FAILURES)
    for r in rows:
        print(f"{r['id']:9s} {r['status']:10s} {r['measured'][:110]}")
    if a.check:
        raise SystemExit(f"new failures: {new}" if new else 0)
    JSON.write_text(json.dumps(rows, indent=1))
    MD.write_text(markdown(rows))
    print("wrote", MD)


if __name__ == "__main__":
    main()
